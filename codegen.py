"""Generate a standalone, human-editable Python script that reproduces a
figure built in the app — using plain seaborn/matplotlib, no dependency on
this project's files.

The actual plotting function's source is embedded verbatim (via inspect),
so the exported script can never drift out of sync with what the app
rendered: it's the same code, just unrolled into a plain file.
"""

import inspect

import plot_builder
import style as style_module


def generate_script(plot_name: str, func, call_kwargs: dict, font_scale: float, show_grid: bool) -> str:
    func_name = func.__name__
    helper_sources = [
        f"FONT_STACK = {style_module.FONT_STACK!r}",
        inspect.getsource(plot_builder.PlotError),
        inspect.getsource(plot_builder._require),
        inspect.getsource(plot_builder._new_fig),
        inspect.getsource(plot_builder._dedupe_labels),
        inspect.getsource(style_module.finalize_axes),
        inspect.getsource(style_module.apply_nature_style),
        inspect.getsource(func),
    ]
    helpers_block = "\n\n".join(s.rstrip() for s in helper_sources)

    kwargs_block = "\n".join(f"    {k}={v!r}," for k, v in call_kwargs.items())
    slug = plot_name.lower().replace(" ", "_").replace("(", "").replace(")", "")

    return f'''"""
Auto-generated by Plot Studio — standalone script to reproduce the
"{plot_name}" figure. Edit freely; only needs pandas, numpy, matplotlib, seaborn.
"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns


{helpers_block}


# ---------------------------------------------------------------- load data
df = pd.read_csv("your_data.csv")  # TODO: point this at your actual data file

# -------------------------------------------------------------- build plot
apply_nature_style(font_scale={font_scale!r}, show_grid={show_grid!r})

fig = {func_name}(
    df,
{kwargs_block}
)

plt.show()
# fig.savefig("{slug}.png", dpi=300, bbox_inches="tight")
# fig.savefig("{slug}.pdf", bbox_inches="tight")
'''
